// Builds tests/ui-inventory.md and tests/ui-audit.md from one audit run's results.
// Usage: npm run audit:report [-- "Run label" [run-id]]   (default: the most recent run)
import fs from "node:fs";
import path from "node:path";

const root = ".e2e-state/audit";
const runs = fs.existsSync(root)
  ? fs.readdirSync(root).filter((d) => fs.statSync(path.join(root, d)).isDirectory())
  : [];
const runId = process.argv[3] ?? runs.sort((a, b) => fs.statSync(path.join(root, b)).mtimeMs - fs.statSync(path.join(root, a)).mtimeMs)[0];
if (!runId) throw new Error(`no audit runs in ${root}; run the audit first`);
const dir = path.join(root, runId);
const all = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".jsonl"))
  .flatMap((f) => fs.readFileSync(path.join(dir, f), "utf8").trim().split("\n").filter(Boolean).map((l) => JSON.parse(l)));
if (!all.length) throw new Error(`no results in ${dir}; run the audit first`);
// A retried page (network blip on a remote run) counts by its final attempt only.
const pageKey = (r) => `${r.viewport}|${r.state}|${r.scheme}|${r.page}`;
const finalAttempt = new Map();
for (const r of all) finalAttempt.set(pageKey(r), Math.max(finalAttempt.get(pageKey(r)) ?? 0, r.attempt ?? 0));
const rows = all.filter((r) => (r.attempt ?? 0) === finalAttempt.get(pageKey(r)));
const retried = [...finalAttempt.values()].filter((a) => a > 0).length;

// Fixes made during the audit, matched against failing or previously failing elements.
const FIXES = JSON.parse(fs.readFileSync("scripts/audit-fixes.json", "utf8"));
const fixFor = (r) => FIXES.find((f) => new RegExp(f.match).test(`${r.page} ${r.element}`))?.fix ?? "";

const STATES = ["logged-out", "demo", "user", "admin"];
const combos = [...new Set(rows.map((r) => `${r.viewport}/${r.scheme}`))].sort();
const label = process.argv[2] ?? new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC";
const esc = (s) => String(s).replaceAll("|", "\\|");

// Group by page + state + element across the viewport/theme combos.
const groups = new Map();
for (const r of rows) {
  const k = `${r.page}\u0000${r.state}\u0000${r.element}`;
  if (!groups.has(k)) groups.set(k, []);
  groups.get(k).push(r);
}
const sorted = [...groups.values()].sort(
  (a, b) => a[0].page.localeCompare(b[0].page) || STATES.indexOf(a[0].state) - STATES.indexOf(b[0].state),
);

// ------------------------------------------------------------------ results table
const fails = rows.filter((r) => r.result === "fail");
let audit = `# UI click-through audit

Run: ${label}. Generated by \`npm run audit:report\` from \`tests/e2e/audit.spec.ts\`.

Every interactive element on every page, in 4 account states (logged out, demo, signed in,
admin) × ${combos.length} viewport/theme combinations (${combos.join(", ")}). Desktop is 1440 px wide,
mobile 390 px. Each element is reached with the mouse and the keyboard (Tab focus + Enter/Space/arrows) and
must do something visible and correct: navigate to the right page (no 404), open a new tab on the right
site, open a menu/dialog (whose contents are then tested too), or update the page. Console errors and failed
requests fail the page. Chat replies are mocked, so the audit makes no model calls.

**${rows.length} checks on ${finalAttempt.size} page × state × viewport × theme combinations: ${rows.length - fails.length} passed, ${fails.length} failed.**
${retried ? `${retried} page run(s) were retried once after a network error; only the final attempt counts.` : "No page needed a retry."}
Shared header/footer elements are tested on one page per layout, so they appear under \`/\` and \`/chat\`.

| Element | Page | State | Result | What it does / fix |
|---|---|---|---|---|
`;
for (const g of sorted) {
  const r0 = g[0];
  const failed = g.filter((r) => r.result === "fail");
  const result = failed.length ? `**FAIL** (${failed.map((r) => `${r.viewport}/${r.scheme}`).join(", ")})` : `pass (${g.length}/${g.length})`;
  const details = [...new Set(g.map((r) => r.detail))].join("; ");
  const fix = fixFor(r0);
  audit += `| ${esc(r0.element)} | ${r0.page} | ${r0.state} | ${result} | ${esc(details)}${fix ? ` · **Fixed:** ${esc(fix)}` : ""} |\n`;
}
audit += `\n## Fixes made during the audit\n\n`;
for (const f of FIXES) audit += `- **${f.title}**: ${f.fix}\n`;
fs.writeFileSync("../tests/ui-audit.md", audit);

// ------------------------------------------------------------------ inventory
let inv = `# UI inventory

Every clickable or editable element on the live site, by page and account state, as found by the
audit crawler (\`tests/e2e/audit.spec.ts\`). Items under "›" live inside a menu or dialog opened by the
element before them. "Header/footer" items are shared by every page using that layout.

`;
const byPage = new Map();
for (const g of sorted) {
  const r = g[0];
  if (!byPage.has(r.page)) byPage.set(r.page, new Map());
  const states = byPage.get(r.page);
  if (!states.has(r.element)) states.set(r.element, { kind: r.kind, states: new Set(), details: new Set() });
  const e = states.get(r.element);
  for (const x of g) {
    e.states.add(x.state);
    e.details.add(x.detail);
  }
}
for (const [page, elements] of byPage) {
  inv += `## \`${page}\`\n\n| Element | Type | States | Does |\n|---|---|---|---|\n`;
  for (const [el, e] of elements) {
    const states = STATES.filter((s) => e.states.has(s)).join(", ");
    inv += `| ${esc(el)} | ${e.kind} | ${states} | ${esc([...e.details].join("; "))} |\n`;
  }
  inv += "\n";
}
fs.writeFileSync("../tests/ui-inventory.md", inv);
console.log(`${rows.length} checks, ${fails.length} failed → tests/ui-audit.md, tests/ui-inventory.md`);
for (const f of fails) console.log(`FAIL ${f.viewport}/${f.scheme} ${f.state} ${f.page} ${f.element}: ${f.detail}`);
